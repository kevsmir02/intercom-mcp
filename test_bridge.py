    async def test_git_summary_and_full_diff(self) -> None:
        self.init_repo()
        tracked = self.workdir / "tracked.txt"
        tracked.write_text("original line\n")
        subprocess.run(["git", "add", "."], cwd=self.workdir, check=True)
        subprocess.run(
            ["git", "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "init"], cwd=self.workdir, check=True
        )
        async with self.session() as session:
            summary_only = await self.call(session, "delegate_to_antigravity", prompt="__WRITE__:newfile.txt")
            full = await self.call(
                session, "delegate_to_antigravity", prompt="__EDIT__:tracked.txt __WRITE__:other.txt", include_diff=True
            )
        self.assertTrue(summary_only.startswith("[SUCCESS]"), summary_only)
        self.assertIn("$ git status --short", summary_only)
        self.assertIn("?? newfile.txt", summary_only)
        self.assertIn("$ git diff --stat HEAD", summary_only)
        self.assertNotIn("$ git diff HEAD (plus untracked", summary_only)

        self.assertTrue(full.startswith("[SUCCESS]"), full)
        self.assertIn(" M tracked.txt", full)
        self.assertIn("$ git diff HEAD (plus untracked files via --no-index)", full)
        self.assertIn("+appended by fake harness", full)
        self.assertIn("+++ b/other.txt", full)
        self.assertIn("+generated by fake harness", full)

    async def test_failure_report_contains_diagnostics_and_call_to_action(self) -> None:
        async with self.session() as session:
            text = await self.call(session, "delegate_to_antigravity", prompt="run tests __FAIL__")
        self.assertTrue(text.startswith("[ROADBLOCK / FAILURE]"), text)
        self.assertIn("Exit code: 3", text)
        self.assertIn("Traceback (most recent call last):", text)
        self.assertIn("AssertionError: expected 3, got -1", text)
        self.assertIn("FAILED tests/test_calc.py::test_add", text)
        self.assertIn("detected diagnostics", text)
        self.assertIn("ACTION REQUIRED", text)
        self.assertIn("Probable cause: Task-level failure", text)

    async def test_timeout_kills_process_tree_and_returns_partial_logs(self) -> None:
        pidfile = self.tmp / "pids.txt"
        started = time.monotonic()
        async with self.session(FAKE_PIDFILE=str(pidfile)) as session:
            text = await self.call(session, "delegate_to_antigravity", prompt="never finish __HANG__", timeout_seconds=2)
        elapsed = time.monotonic() - started
        self.assertTrue(text.startswith("[TIMEOUT_ERROR]"), text)
        self.assertIn("exceeded 2s", text)
        self.assertIn("starting long job (partial log line)", text)
        self.assertIn("partial stdout", text)
        self.assertLess(elapsed, 15, "timeout handling took too long (escalation to SIGKILL broken?)")
        pids = [int(p) for p in pidfile.read_text().split()]
        self.assertEqual(len(pids), 2, "fake harness should record its own pid and its child's pid")
        self.assertEqual(_wait_dead(pids), [], "harness process tree survived the timeout")

    async def test_missing_binary_is_reported_as_roadblock(self) -> None:
        async with self.session(AGY_BIN=str(self.tmp / "nope" / "agy")) as session:
            text = await self.call(session, "delegate_to_antigravity", prompt="x")
        self.assertTrue(text.startswith("[ROADBLOCK / FAILURE]"), text)
        self.assertIn("not found", text)
        self.assertIn("check_antigravity_health", text)


