def _wait_dead(pids: list[int], timeout: float = 5.0) -> list[int]:
    """Poll until every pid is gone (or a zombie); return the survivors."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if not any(bridge._pid_alive(p) for p in pids):
            return []
        time.sleep(0.1)
    return [p for p in pids if bridge._pid_alive(p)]


def result_text(result) -> str:
    return "\n".join(getattr(c, "text", "") for c in result.content if getattr(c, "type", "") == "text")


def input_schema(tool) -> dict:
    """mcp 2.x exposes Tool.input_schema, mcp 1.x Tool.inputSchema."""
    schema = getattr(tool, "input_schema", None)
    if schema is None:
        schema = getattr(tool, "inputSchema")
    return schema


CONFIG_KEYS = {"AGY_BIN", "AGY_AUTO_APPROVE_FLAGS", "AGY_DEFAULT_FLAGS", "CLAUDE_BIN", "CLAUDE_AUTO_APPROVE_FLAGS",
               "CLAUDE_DEFAULT_FLAGS", "CLAUDECODE"}


class BridgeTestCase(unittest.IsolatedAsyncioTestCase):
    """Shared fixture: temp dir with fake binaries, a work dir, and an env for the server."""

    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="harness-bridge-test-"))
        self.fake_dir = self.tmp / "bin"
        self.fake_dir.mkdir()
        self.fake_agy = self._install_fake("agy")
        self.fake_claude = self._install_fake("claude")
        self.workdir = self.tmp / "project"
        self.workdir.mkdir()

    def _install_fake(self, name: str) -> Path:
        path = self.fake_dir / name
        path.write_text(FAKE_HARNESS)
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        return path

    def tearDown(self) -> None:
        shutil.rmtree(self.tmp, ignore_errors=True)

    def server_env(self, **overrides: str) -> dict[str, str]:
        env = {
            k: v
            for k, v in os.environ.items()
            if k not in CONFIG_KEYS and not k.startswith(("BRIDGE_", "FAKE_", "CLAUDE_CODE_"))
        }
        env.update(
            {
                "AGY_BIN": str(self.fake_agy),
                "CLAUDE_BIN": str(self.fake_claude),
                "BRIDGE_KILL_GRACE_SECONDS": "1",
                "BRIDGE_LOG_LEVEL": "WARNING",
            }
        )
        env.update(overrides)
        return env

    @contextlib.asynccontextmanager
    async def session(self, env: dict[str, str] | None = None, **overrides: str):
        params = StdioServerParameters(
            command=sys.executable, args=[str(SERVER)], env=env if env is not None else self.server_env(**overrides)
        )
        async with stdio_client(params) as (read, write):
            async with ClientSession(read, write) as session:
                await session.initialize()
                yield session

    async def call(self, session: ClientSession, tool: str, **arguments) -> str:
        if tool.startswith("delegate_to_"):
            arguments.setdefault("working_dir", str(self.workdir))
        return result_text(await session.call_tool(tool, arguments))

    def init_repo(self) -> None:
        if not shutil.which("git"):
            self.skipTest("git not installed")
        subprocess.run(["git", "init", "-q"], cwd=self.workdir, check=True)


