@unittest.skipUnless(os.name == "posix", "uses bash")
class TestProcessRunner(unittest.IsolatedAsyncioTestCase):
    async def test_cancellation_kills_process_tree(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            pidfile = Path(tmp) / "pids"
            script = (
                "trap '' TERM; ( trap '' TERM; exec sleep 300 ) & c=$!; "
                f"printf '%s\\n%s\\n' $$ $c > {pidfile}; wait $c"
            )
            task = asyncio.ensure_future(bridge.run_process(["bash", "-c", script], cwd=tmp, timeout=60, kill_grace=1))
            for _ in range(50):
                await asyncio.sleep(0.1)
                if pidfile.exists() and len(pidfile.read_text().split()) == 2:
                    break
            pids = [int(p) for p in pidfile.read_text().split()]
            task.cancel()
            with self.assertRaises(asyncio.CancelledError):
                await task
            self.assertEqual(_wait_dead(pids), [], "process tree survived task cancellation")

    async def test_timeout_returns_partial_output_and_kills_tree(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            pidfile = Path(tmp) / "pids"
            script = (
                "echo partial-out; echo partial-err >&2; trap '' TERM; ( trap '' TERM; exec sleep 300 ) & c=$!; "
                f"printf '%s\\n%s\\n' $$ $c > {pidfile}; wait $c"
            )
            result = await bridge.run_process(["bash", "-c", script], cwd=tmp, timeout=1, kill_grace=1)
            self.assertTrue(result.timed_out)
            self.assertIsNone(result.returncode)
            self.assertIn("partial-out", result.stdout)
            self.assertIn("partial-err", result.stderr)
            pids = [int(p) for p in pidfile.read_text().split()]
            self.assertEqual(_wait_dead(pids), [], "process tree survived the timeout")

    async def test_normal_exit_codes_are_reported(self) -> None:
        ok = await bridge.run_process(["bash", "-c", "echo hi; exit 0"], cwd="/", timeout=10, kill_grace=1)
        self.assertEqual((ok.returncode, ok.stdout.strip(), ok.timed_out), (0, "hi", False))
        bad = await bridge.run_process(["bash", "-c", "echo oops >&2; exit 7"], cwd="/", timeout=10, kill_grace=1)
        self.assertEqual((bad.returncode, bad.stderr.strip()), (7, "oops"))
        fed = await bridge.run_process(["cat"], cwd="/", timeout=10, stdin_data=b"from-stdin", kill_grace=1)
        self.assertEqual(fed.stdout, "from-stdin")


