@unittest.skipUnless(os.name == "posix", "fake harnesses need a POSIX shell environment")
class TestValidation(BridgeTestCase):
    async def test_missing_working_dir_is_rejected_before_execution(self) -> None:
        missing = self.tmp / "does-not-exist"
        async with self.session() as session:
            text = await self.call(session, "delegate_to_antigravity", prompt="hello", working_dir=str(missing))
        self.assertTrue(text.startswith("[INVALID_ARGUMENT]"), text)
        self.assertIn("does not exist", text)
        self.assertIn(str(missing), text)
        self.assertNotIn("FAKE_ARGS", text)  # the harness was never launched

    async def test_file_instead_of_directory_is_rejected(self) -> None:
        file_path = self.tmp / "file.txt"
        file_path.write_text("x")
        async with self.session() as session:
            text = await self.call(session, "delegate_to_claude_code", prompt="hello", working_dir=str(file_path))
        self.assertTrue(text.startswith("[INVALID_ARGUMENT]"), text)
        self.assertIn("not a directory", text)

    async def test_bad_prompt_timeout_flags_and_conversation_id(self) -> None:
        async with self.session() as session:
            empty = await self.call(session, "delegate_to_antigravity", prompt="   ")
            bad_timeout = await self.call(session, "delegate_to_antigravity", prompt="x", timeout_seconds=0)
            interactive = await self.call(session, "delegate_to_antigravity", prompt="x", flags=["-i"])
            double_print = await self.call(session, "delegate_to_claude_code", prompt="x", flags=["--print"])
            resume_flag = await self.call(session, "delegate_to_claude_code", prompt="x", flags=["--resume", "abc"])
            bad_conv = await self.call(session, "delegate_to_antigravity", prompt="x", conversation_id="--evil flag")
        for text in (empty, bad_timeout, interactive, double_print, resume_flag, bad_conv):
            self.assertTrue(text.startswith("[INVALID_ARGUMENT]"), text)
        self.assertIn("prompt", empty)
        self.assertIn("timeout_seconds", bad_timeout)
        self.assertIn("interactive", interactive)
        self.assertIn("prompt argument", double_print)
        self.assertIn("conversation_id", resume_flag)
        self.assertIn("conversation_id", bad_conv)


